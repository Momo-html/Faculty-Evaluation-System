    public static function classifyRating(float $rating): string
    {
        foreach (self::performanceScale() as $scale) {
            if ($rating >= $scale['min'] && $rating <= $scale['max']) {
                return $scale['label'];
            }
        }

        return $rating > 0 ? 'Unclassified' : 'No Rating';
    }

    public static function classificationClass(string $classification): string
    {
        return str_replace(' ', '-', strtolower($classification));
    }

    public static function ratingScaleMax(): float
    {
        return 4.00;
    }

    public static function minimumReliableResponses(): int
    {
        return max(1, (int) self::value('minimum_reliable_responses', '10'));
    }

    /**
     * @return array{label: string, class: string}
     */
    public static function reliabilityFor(int $responses): array
    {
        if ($responses >= self::minimumReliableResponses()) {
            return ['label' => 'Reliable', 'class' => 'reliable'];
        }

        return [
            'label' => 'Low response count. Result should be reviewed with caution.',
            'class' => 'low',
        ];
    }

    /**
     * @return array<string, mixed>
     */
    public static function all(): array
    {
        $defaults = self::defaults();

        if (! Schema::hasTable('settings')) {
            return $defaults;
        }

        $stored = Setting::query()->pluck('value', 'key')->all();

        return array_replace($defaults, array_intersect_key($stored, $defaults));
    }

    public static function value(string $key, mixed $default = null): mixed
    {
        return self::all()[$key] ?? $default;
    }

    public static function enabled(string $key, bool $default = false): bool
    {
        return (string) self::value($key, $default ? '1' : '0') === '1';
    }

    public static function imageUrl(string $pathKey, ?string $fallback = null): ?string
    {
        $path = self::value($pathKey);

        if (is_string($path) && $path !== '') {
            return asset('storage/'.ltrim($path, '/'));
        }

        return $fallback;
    }

    public static function imagePathForPdf(string $pathKey): ?string
    {
        $path = self::value($pathKey);

        if (! is_string($path) || $path === '') {
            return null;
        }

        $fullPath = Storage::disk('public')->path($path);

        return is_file($fullPath) ? $fullPath : null;
    }
